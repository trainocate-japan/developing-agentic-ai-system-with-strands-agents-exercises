@mcp.tool
def search_kb(query: str) -> str:
    """社内ナレッジベースをキーワードで検索し、該当する記事のタイトルと記事IDを返す。

    FAQに含まれない、経費精算・会議室予約システムの使い方・名刺発注・
    社用スマートフォンの紛失対応・在宅勤務時のセキュリティ・健康診断の予約など、
    社内手続きに関する幅広い質問に使う。

    Args:
        query: 検索キーワードまたは質問文
    """
    hits = [
        f"[{article_id}] {article['title']}"
        for article_id, article in KB_ARTICLES.items()
        if any(keyword in query for keyword in article["keywords"])
    ]
    if hits:
        return "\n".join(hits)
    return "該当する記事が見つかりませんでした。"


@mcp.tool
def get_article(article_id: str) -> str:
    """記事IDから、社内ナレッジベースの記事本文を取得する。

    search_kbで見つけた記事IDについて、詳しい内容を確認したい場合に使う。

    Args:
        article_id: 記事ID(例: KB-001)
    """
    article = KB_ARTICLES.get(article_id)
    if not article:
        return f"記事ID {article_id} は見つかりませんでした。"
    return f"[{article['title']}]\n{article['body']}"


